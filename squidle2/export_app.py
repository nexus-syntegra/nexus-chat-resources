"""Write the Squidle2 swoop app icon and the bare pixel mascot into the app, its site and this repo.

usage: python export_app.py <nexus-chat-android> <site-nexus-syntegra>
"""
import re
import sys
from pathlib import Path

from PIL import Image

from render import (
    CATCH_SIDE,
    CYAN,
    PURPLE,
    body_ramp,
    body_t,
    catchlights,
    cell_rgb,
    cells,
    draw_mascot,
    oklch_to_rgb,
    plain,
    tone,
)
from render_art import OFF, SCALE, S, quantize, quantize_layers

HERE = Path(__file__).parent
GENERATED = "Generated by nexus-chat-resources/squidle2/export_app.py: edit the generator, not this file."


def launcher_layers(px=432):
    """Adaptive-icon layers, 108dp at xxxhdpi.

    The whole composition sits in the 72dp viewport every launcher mask stays inside. The 18dp
    bleed around it, seen only during parallax and reveal animations, repeats the composition's
    edge pixels outward so no seam shows where the glow meets it.
    """
    bg, front = quantize_layers(frame=True)
    d = px * 2 // 3
    inset = (px - d) // 2
    art = bg.resize((d, d), Image.LANCZOS)
    back = Image.new("RGB", (px, px))
    back.paste(art.crop((0, 0, d, 1)).resize((d, inset)), (inset, 0))
    back.paste(art.crop((0, d - 1, d, d)).resize((d, inset)), (inset, inset + d))
    back.paste(art.crop((0, 0, 1, d)).resize((inset, d)), (0, inset))
    back.paste(art.crop((d - 1, 0, d, d)).resize((inset, d)), (inset + d, inset))
    for (cx, cy), (bx, by) in (((0, 0), (0, 0)), ((d - 1, 0), (inset + d, 0)),
                               ((0, d - 1), (0, inset + d)), ((d - 1, d - 1), (inset + d, inset + d))):
        back.paste(art.getpixel((cx, cy)), (bx, by, bx + inset, by + inset))
    back.paste(art, (inset, inset))
    fg = Image.new("RGBA", (d, d), (0, 0, 0, 0))
    draw_mascot(fg, d, SCALE, (0, OFF[1] * d / S))
    fg.alpha_composite(front.resize((d, d), Image.LANCZOS))
    fore = Image.new("RGBA", (px, px), (0, 0, 0, 0))
    fore.paste(fg, (inset, inset))
    return back, fore


def num(v):
    return f"{v:.3f}".rstrip("0").rstrip(".")


def vector(dp, viewport, cell, ox, oy, color_of, catchlight=None, extra=()):
    """Pixel-art vector drawable: one path per colour, one rectangle per horizontal run.

    `catchlight` fills the sub-cell glint in each pupil; None leaves it out. `extra` adds
    (colour, ((x, y, w, h), ...)) rectangles in cells, on the same grid as the mascot.
    """
    runs = {}
    for gy in sorted({gy for _, gy, _ in cells()}):
        row = sorted((gx, ch) for gx, y, ch in cells() if y == gy)
        start = prev = None
        for gx, ch in row + [(None, None)]:
            col = color_of(gx, gy, ch) if ch else None
            if start is not None and (col != start[1] or gx != prev + 1):
                x, y, w = ox + start[0] * cell, oy + gy * cell, (prev + 1 - start[0]) * cell
                runs.setdefault(start[1], []).append(f"M{num(x)},{num(y)}h{num(w)}v{num(cell)}h{num(-w)}z")
                start = None
            if col and start is None:
                start = (gx, col)
            prev = gx
    for col, rects in extra:
        for x, y, w, h in rects:
            x, y, w, h = ox + x * cell, oy + y * cell, w * cell, h * cell
            runs.setdefault(col, []).append(f"M{num(x)},{num(y)}h{num(w)}v{num(h)}h{num(-w)}z")
    layers = list(runs.items())
    if catchlight:
        # Its own last path: merged into the eye whites' path it would sit under the pupils.
        k = CATCH_SIDE * cell
        layers.append((catchlight, [f"M{num(ox + gx * cell)},{num(oy + gy * cell)}h{num(k)}v{num(k)}h{num(-k)}z"
                                    for gx, gy in catchlights()]))
    paths = "\n".join(f'    <path\n        android:fillColor="{c}"\n        android:pathData="{"".join(p)}" />'
                      for c, p in layers)
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- {GENERATED} -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{dp}dp"
    android:height="{dp}dp"
    android:viewportWidth="{viewport}"
    android:viewportHeight="{viewport}">
{paths}
</vector>
'''


def hexrgb(rgb):
    return "#{:02X}{:02X}{:02X}".format(*rgb)


def colored(gx, gy, ch):
    return hexrgb(cell_rgb(gx, gy, ch))


def silhouette(gx, gy, ch):
    """One ink with the pupils cut out as dot eyes. Cutting the eye whites instead leaves an
    L-shaped hole that reads as a scowl, and cutting whole eyes reads as a skull."""
    return None if ch in "dk" else "#FFFFFFFF"


# The help icon's question marks, one each side of the head with a cell of air between.
QUESTION_MARKS = ((CYAN, ((4, 5, 2, 1), (5, 6, 1, 1), (4, 7, 1, 1), (4, 9, 1, 1))),
                  (PURPLE, ((19, 4, 2, 1), (20, 5, 1, 1), (19, 6, 1, 1), (19, 8, 1, 1))))

RESTYLED = ("Colours applied by nexus-chat-resources/squidle2/export_app.py from the section comments: "
            "edit shapes here, the palette there.")
# Section comment -> cell kind. First match wins, so the inner shadow is not taken for the mouth.
ROLES = (("Mouth inner shadow", "mouth_inner"), ("=== MOUTH", "mouth"), ("=== BODY HIGHLIGHT", "c"),
         ("=== BODY SHADOW", "f"), ("=== BODY", "b"), ("=== TENTACLES", "b"))
RECT = re.compile(r'(\s*)<path android:fillColor="#[0-9A-Fa-f]{6}" android:pathData="M(\d+),(\d+) h(\d+) v(\d+) h-\d+ z" />')


def role_rgb(role, t):
    if role.startswith("mouth"):
        # A dark opening tinted by the body around it.
        _, _, H = body_ramp(t)
        return oklch_to_rgb(0.34 if role == "mouth_inner" else 0.45, 0.11, H)
    return tone(t, role)


def restyle(path, unit):
    """Recolour a hand-drawn Squidle vector drawable with the body's diagonal light.

    Shapes stay as drawn; each body cell (`unit` viewport units square, on the mascot's
    24-cell grid) takes the colour of its place in the light. Sections whose comment names
    no role (eyes, blush) keep their colours.
    """
    out, role = [], None
    for line in path.read_text().splitlines():
        if "<!--" in line:
            role = next((r for key, r in ROLES if key in line), role if "===" not in line else None)
            out.append(line)
            continue
        if role is None or "<path" not in line:
            out.append(line)
            continue
        m = RECT.fullmatch(line)
        if not m:
            raise ValueError(f"{path}: not a rectangle path: {line.strip()}")
        indent, x, y, w, h = m.group(1), *map(int, m.groups()[1:])
        if x % unit or y % unit or w % unit or h % unit:
            # Off the cell grid: one colour, from the shape's centre.
            t = body_t((x + w / 2) / unit - 0.5, (y + h / 2) / unit - 0.5)
            out.append(f'{indent}<path android:fillColor="{hexrgb(role_rgb(role, t))}" '
                       f'android:pathData="M{x},{y} h{w} v{h} h-{w} z" />')
            continue
        for gy in range(y // unit, (y + h) // unit):
            runs = []
            for gx in range(x // unit, (x + w) // unit):
                col = hexrgb(role_rgb(role, body_t(gx, gy)))
                if runs and runs[-1][0] == col:
                    runs[-1][2] += 1
                else:
                    runs.append([col, gx, 1])
            out.extend(f'{indent}<path android:fillColor="{col}" android:pathData="M{gx * unit},{gy * unit} '
                       f'h{n * unit} v{unit} h-{n * unit} z" />' for col, gx, n in runs)
    if RESTYLED not in out[1]:
        out.insert(1, f"<!-- {RESTYLED} -->")
    return "\n".join(out) + "\n"


def write(path, data):
    path.parent.mkdir(parents=True, exist_ok=True)
    if isinstance(data, str):
        path.write_text(data)
    else:
        data.save(path, optimize=True)
    print(path)


def main(android, site):
    android, site = Path(android), Path(site)
    back, fore = launcher_layers()
    for module in ("app", "wear"):
        res = android / module / "src/main/res"
        write(res / "drawable-nodpi/ic_launcher_background.png", back)
        write(res / "drawable-nodpi/ic_launcher_foreground.png", fore)
    res = android / "app/src/main/res/drawable"
    # Same 108dp frame as the launcher foreground layer, so themed icons line up with it.
    c = 72 / 24 * SCALE
    write(res / "ic_launcher_monochrome.xml", vector(108, 108, c, 54 - 12 * c, 54 - 12.5 * c, silhouette))
    # In-app mascot: the chat indicator's sizes and overlays assume a 108dp frame with the body
    # in a 42x45 box centred at (54, 52.5).
    c = 45 / 13
    write(res / "ic_squidle.xml", vector(108, 108, c, 54 - 12 * c, 52.5 - 12.5 * c, colored, "#FFFFFF"))
    stat = vector(24, 24, 1, 0, 0, silhouette)
    write(res / "ic_stat_squidle.xml", stat)
    # The watch's notification and complication glyph.
    write(android / "wear/src/main/res/drawable/ic_stat_squidle.xml", stat)
    write(res / "ic_squidle_help.xml", vector(24, 24, 1, 0, 0, colored, "#FFFFFF", QUESTION_MARKS))
    for n in (1, 2, 3):
        write(res / f"squidle_talk_{n}.xml", restyle(res / f"squidle_talk_{n}.xml", 2))

    icon = quantize(frame=True)
    write(HERE / "squidle2_play_icon_512.png", icon.resize((512, 512), Image.LANCZOS).convert("RGB"))
    write(android / "branding/play/icon_512.png", icon.resize((512, 512), Image.LANCZOS).convert("RGB"))
    write(site / "public/nexus_squid_icon_tight.png", icon.resize((512, 512), Image.LANCZOS).convert("RGB"))
    write(site / "public/nexus_squid_icon_192.png", icon.resize((192, 192), Image.LANCZOS).convert("RGB"))
    write(HERE.parent / "squidle_icon.png", plain(1024, (255, 255, 255, 255)))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
